const T0 = '2026-08-19T08:00:00.000Z'
const daysAgo = (n) => addDays(T0, -n)

function slaDue(stage, startedAt) {
  return addDays(startedAt, DEFAULT_SLA_DAYS[stage] || 7)
}

function audit(actorId, action, detail, at) {
  return { id: uid('aud'), at, actorId, action, detail }
}

function billing(milestone, percent, amountEx, status, at, extras = {}) {
  return {
    id: uid('bill'),
    milestone,
    percent,
    amountEx,
    gst: gstOn(amountEx),
    status,
    invoiceNumber: extras.invoiceNumber || '',
    paymentStatus: extras.paymentStatus || 'unpaid',
    createdAt: at,
    event: extras.event,
  }
}

